def synthesize(text: str, voice: str, emotion: str, out_path: str, max_retries: int = 3) -> bool:
    encoded = urllib.parse.quote(text)
    url = f"{API_BASE}/synthesize_speech/?text={encoded}&voice={voice}&emotion={emotion}&speed=1.0"
    
    for attempt in range(max_retries):
        try:
            print(f"  Attempt {attempt+1}: synthesizing {len(text)} chars...")
            urllib.request.urlretrieve(url, out_path)
            size = os.path.getsize(out_path)
            print(f"  OK: {size} bytes")
            return True
        except Exception as e:
            print(f"  Error: {e}")
            if attempt < max_retries - 1:
                time.sleep(5)
    return False

def create_silence(out_path: str, duration: float = 0.8):
    cmd = [
        "ffmpeg", "-y", "-f", "lavfi",
        "-i", f"anullsrc=r=24000:cl=mono",
        "-t", str(duration),
        "-acodec", "pcm_s16le",
        out_path
    ]
    subprocess.run(cmd, capture_output=True, check=True)

def main():
    segments = []
    failed = []
    
    # Generate each segment
    for i, (voice, text) in enumerate(SCRIPT):
        emotion = "neutral"
        seg_path = os.path.join(OUTPUT_DIR, f"podcast_ai_seg_{i:02d}_{voice}.wav")
        silence_path = os.path.join(OUTPUT_DIR, f"podcast_ai_silence_{i:02d}.wav")
        
        print(f"\n[{i+1}/{len(SCRIPT)}] voice={voice}, emotion={emotion}")
        print(f"  Text: {text[:60]}...")
        
        if os.path.exists(seg_path) and os.path.getsize(seg_path) > 1000:
            print(f"  Cached: {os.path.getsize(seg_path)} bytes")
        else:
            ok = synthesize(text, voice, emotion, seg_path)
            if not ok:
                failed.append(i)
                print(f"  FAILED segment {i}")
                continue
        
        # Create silence after segment
        create_silence(silence_path)
        segments.append(seg_path)
        segments.append(silence_path)
    
    print(f"\nGenerated {len(SCRIPT) - len(failed)} segments, {len(failed)} failed")
    if failed:
        print(f"Failed indices: {failed}")
    
    if not segments:
        print("No segments generated!")
        return
    
    # Create file list for ffmpeg concat
    list_path = os.path.join(OUTPUT_DIR, "podcast_concat_list.txt")
    with open(list_path, "w") as f:
        for seg in segments:
            f.write(f"file '{seg}'\n")
    
    print(f"\nConcatenating {len(segments)} files...")
    
    # Concatenate all
    concat_wav = os.path.join(OUTPUT_DIR, "podcast_ai_concat.wav")
    cmd = [
        "ffmpeg", "-y", "-f", "concat", "-safe", "0",
        "-i", list_path,
        "-acodec", "pcm_s16le",
        concat_wav
    ]
    result = subprocess.run(cmd, capture_output=True, text=True)
    if result.returncode != 0:
        print("Concat error:", result.stderr[-500:])
        return
    
    # Convert to mp3
    cmd = [
        "ffmpeg", "-y", "-i", concat_wav,
        "-acodec", "libmp3lame", "-q:a", "4",
        FINAL_OUTPUT
    ]
    result = subprocess.run(cmd, capture_output=True, text=True)
    if result.returncode != 0:
        print("MP3 error:", result.stderr[-500:])
        return
    
    # Stats
    if os.path.exists(FINAL_OUTPUT):
        size = os.path.getsize(FINAL_OUTPUT)
        # Estimate duration from WAV
        wav_size = os.path.getsize(concat_wav) if os.path.exists(concat_wav) else 0
        duration = wav_size / 2 / 24000 if wav_size else 0
        print(f"\n✓ Final file: {FINAL_OUTPUT}")
        print(f"  Size: {size / 1024 / 1024:.2f} MB ({size} bytes)")
        print(f"  Estimated duration: {duration:.1f} seconds ({duration/60:.1f} minutes)")
        print(f"  Segments generated: {len(SCRIPT) - len(failed)}/{len(SCRIPT)}")
    else:
        print("FAILED: output file not created")

if __name__ == "__main__":
    main()
