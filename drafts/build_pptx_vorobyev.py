# ── helper: set paragraph text with formatting ──────────────────────────────
def set_tf(tf, text, size=None, bold=None, color=None, align=None):
    tf.clear()
    lines = text.split('\n')
    for i, line in enumerate(lines):
        if i == 0:
            para = tf.paragraphs[0]
        else:
            para = tf.add_paragraph()
        if align:
            para.alignment = align
        run = para.add_run()
        run.text = line
        if size:
            run.font.size = Pt(size)
        if bold is not None:
            run.font.bold = bold
        if color:
            run.font.color.rgb = color

# ── helper: add text box ─────────────────────────────────────────────────────
def add_textbox(slide, left, top, width, height, text, size=16, bold=False,
                color=None, align=PP_ALIGN.LEFT, wrap=True):
    txBox = slide.shapes.add_textbox(left, top, width, height)
    tf = txBox.text_frame
    tf.word_wrap = wrap
    set_tf(tf, text, size=size, bold=bold, color=color or DARK, align=align)
    return txBox

# ── helper: add red accent line ───────────────────────────────────────────────
def add_line(slide, left, top, width):
    from pptx.util import Pt as Pt2
    from pptx.enum.shapes import MSO_SHAPE_TYPE
    from pptx.oxml.ns import qn as qn2
    # Use a thin rectangle as line
    line = slide.shapes.add_shape(
        1,  # MSO_SHAPE_TYPE.RECTANGLE
        left, top, width, Pt(2)
    )
    line.fill.solid()
    line.fill.fore_color.rgb = RED
    line.line.fill.background()
    return line

